"""Generate names/values only. No sensor protocol implementation lives in C#."""
from pathlib import Path
import re
root=Path(__file__).resolve().parents[1]
headers='\n'.join((root/'include/polar'/f).read_text(encoding='utf-8-sig') for f in ['polar_sdk.h','polar_services.h'])
output=['// Generated by scripts/generate-unity-enums.py from the public C ABI.', 'namespace Polar.Native', '{']
for prefix,enum in [('POLAR_SERVICE_','Service'),('POLAR_EVENT_','EventType'),('POLAR_FEATURE_','Feature')]:
    fields=re.findall(r'\b'+prefix+r'(\w+)\s*=\s*(\d+)\b',headers)
    output.append('    public enum '+enum+' : uint { '+', '.join(''.join(part.title() for part in name.split('_'))+'='+value for name,value in fields)+' }')
output.append('}')
(root/'unity/com.polarble.sdk/Runtime/NativeEnums.cs').write_text('\n'.join(output)+'\n',encoding='utf-8')
